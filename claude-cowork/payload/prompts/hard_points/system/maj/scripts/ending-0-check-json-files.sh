#!/usr/bin/env bash
# ending-0-check-json-files.sh - Check existence of structure JSON files
# Usage: ending-0-check-json-files.sh

if [ -n "$BASH_VERSION" ]; then
  set -euo pipefail
else
  set -eu
fi

echo "🔍 Checking structure files..."

MISSING=false

if [ ! -f "/tmp/aikido/maj_target.json" ]; then
  echo "❌ ERROR: File /tmp/aikido/maj_target.json missing"
  echo "   This file should have been generated by plan-beginning (Phase 5)"
  MISSING=true
fi

if [ ! -f "/tmp/aikido/maj_before.json" ]; then
  echo "❌ ERROR: File /tmp/aikido/maj_before.json missing"
  echo "   This file should have been generated by plan-beginning (Phase 5)"
  MISSING=true
fi

if [ "$MISSING" = true ]; then
  exit 1
fi

echo "✅ Structure files detected"
exit 0
